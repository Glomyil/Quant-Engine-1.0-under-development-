#   fn        ：上面那些函数（签名必须统一）
#   sign      ：+1 = 值越大越看多；-1 = 值越小越看多（**方向只写在这里**）
#   requires  ：需要面板里的哪些表。bt.py 会先检查，缺表就跳过并打印原因
#   note      ：出现在报告头部的一句话说明
#
# ⚠️ 相关性预警（写报告时必须提）：
#   rev_5d / rev_20d / ma_dev_20 / vol_20d 都是从**同一个价格序列**派生的，
#   彼此高度相关 → 它们不是"N 个独立发现"，只是同一现象的几种量法。
#   下一步要做的：算因子之间的截面相关系数矩阵，再做正交化。
FACTORS: dict[str, dict] = {
    "rev_5d":    {"fn": rev_5d,    "sign": -1, "requires": ["close_adj"],
                  "note": "5 日反转"},
    "rev_20d":   {"fn": rev_20d,   "sign": -1, "requires": ["close_adj"],
                  "note": "20 日反转(样板)"},
    "mom_120d":  {"fn": mom_120d,  "sign": +1, "requires": ["close_adj"],
                  "note": "6 个月动量"},
    "vol_20d":   {"fn": vol_20d,   "sign": -1, "requires": ["close_adj"],
                  "note": "20 日波动率(低波动异象)"},
    "ma_dev_20": {"fn": ma_dev_20, "sign": -1, "requires": ["close_adj"],
                  "note": "均线偏离(乖离率)"},
    "amihud_20": {"fn": amihud_20, "sign": +1, "requires": ["close_adj", "amount"],
                  "note": "Amihud 非流动性"},
}
