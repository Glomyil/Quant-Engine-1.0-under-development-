"""sandbox/factors.py —— 因子清单（你扩展因子的唯一入口）

===============================================================================
一、这个文件在整个闭环里的位置
===============================================================================
    面板(宽表)  ──[因子函数]──►  因子宽表(同形状)  ──[sign 定向]──►  分层/IC/多空
    5,471 只 × 2,839 天          每个格子一个"打分"        大 = 看多

二、加一个因子 = 三步
    1) 写一个函数：fn(panels, params) -> DataFrame，和下面这些长得一样
    2) 在 FACTORS 里登记一行：{"fn":..., "sign":±1, "requires":[...], "note":"..."}
    3) 把名字填进 bt.py 顶部的 FACTOR_LIST，跑  python -m sandbox.bt

三、三条不可破的约定
    ① 签名统一：fn(panels, params) -> DataFrame（index=交易日, columns=代码）
    ② 只返回**原始值**：不要在这里取负号、排名、标准化。方向交给 registry 的 sign
    ③ "requires" 声明需要 panels 里的哪些表；缺表会被 bt.py 跳过并打印原因
       —— 宁可当场报错，也不要悄悄算出一堆 NaN

四、方向（sign）为什么这么重要
    sign = +1 ：因子值越大 → 越看多（动量类）
    sign = -1 ：因子值越小 → 越看多（反转类、低波动类）
    定向之后，**层4 永远是"看多档"、层0 永远是"看空档"** —— 这样 6 个因子的
    结果才能横着比。如果方向混着写，你会看到一张读不出结论的对比表。

五、看一个因子好不好，按顺序问三个问题
    1) 方向对不对：IC 均值符号 + 分层单调性（层0→层4 是不是单向）
    2) 稳不稳：ICIR（= IC均值 / IC标准差）、分区间是否一致、样本外
    3) 独立不独立：和我们已有的因子相关系数多少？如果 0.9，那就是同一个因子
    ⚠️ 还有第 4 件事：换手率。换手 70%/月的因子，对费率的敏感度是 26%/月 的两倍多。

六、文献线索（🔶 = 只是线索，具体结论请自己核）
    rev_*   🔶 De Bondt & Thaler (1985) 反应过度/反转；A 股短期反转更明显（待核）
    mom_*   🔶 Jegadeesh & Titman (1993) 动量；A 股动量弱、反转强（待核）
    vol_20d 🔶 Ang, Hodrick, Xing & Zhang (2006) 低波动异象
    amihud  🔶 Amihud (2002) 非流动性溢价 = |收益| / 成交额
    ma_dev  —— 技术派的"乖离率"，学术上可归到短期过度反应，无单一经典文献
"""
from __future__ import annotations

import pandas as pd


# =============================================================================
# 公共工具：因子统一用什么价格
# =============================================================================
def _px(panels: dict) -> pd.DataFrame:
    """返回"算因子用的价格"：收盘价 ffill（停牌/缺价期间视为价格不变）

    为什么必须 ffill：
        A 股停牌期间价格是 NaN。如果直接 pct_change，停牌前后那几天全是 NaN，
        复牌那天的收益也拿不到 —— 相当于**静默地把样本缩小了**，
        而且缩小得没有规律（停牌越多的股票越容易被丢掉）。

    为什么"ffill 算因子"和"成交价绝不 ffill"不矛盾：
        - 算因子/估值：用的是"账面价"，停牌期间说"价格没变"是符合事实的近似；
        - 成交（open_adj）：用的是真金白银的价格，填出来的价格 = 凭空交易。
        **同一份数据，两种用途，两套口径** —— 这是整个项目里最容易搞混的地方之一。

    fill_method=None 是干嘛的：
        pandas 2.x 的 pct_change 默认 fill_method="pad"（已弃用会告警），
        我们已经在外面显式 ffill 过了，所以这里写 None：既消掉告警，也表明
        "ffill 这件事是我自己做的、我知道我在做什么"。
    """
    return panels["close_adj"].ffill()


# =============================================================================
# 因子 1：rev_5d —— 5 日反转
# =============================================================================
# 一句话    ：过去 5 个交易日跌得最多的股票，下周/下个月倾向反弹。
# 公式      ：factor = close_t / close_{t-5} - 1        （原始值，越大 = 涨越多）
# 方向      ：sign = -1（值越小越看多）→ 层4 = "过去 5 日跌最多" = 看多档
# 经济故事  ：① 短期过度反应：一周内的暴跌常常掺进恐慌/流动性冲击，冲击消退后回补
#             ② 与 20 日反转是"同一个故事的不同时间尺度"
#             ③ 窗口越短 → 信号越新鲜，但换手越高、被费率吃掉的越多
# 计算细节  ：pct_change(5)；前 5 行必然 NaN（窗口不够）
# 常见坑    ：① 窗口太短会混进"微观噪音"（买卖价差、停复牌跳变）
#             ② 换手高：实测 70%/月 → 单边费 0.05% 相当于每年吃掉约 0.8% 的收益
# 与别人关系：与 rev_20d 方向一致但更"抖"；实测 ICIR 0.197 vs rev_20d 的 0.405
def rev_5d(panels: dict, params: dict) -> pd.DataFrame:
    """5 日反转：过去 5 个交易日的收益率（原始值）"""
    return _px(panels).pct_change(5, fill_method=None)


# =============================================================================
# 因子 2：rev_20d —— 20 日反转（v0 的样板因子）
# =============================================================================
# 一句话    ：过去一个月跌得多的，下个月倾向涨回来。
# 公式      ：factor = close_t / close_{t-20} - 1
# 方向      ：sign = -1 → 层0 = 过去涨最多（看空档），层4 = 过去跌最多（看多档）
# 经济故事  ：① 反应过度后的修正（🔶 De Bondt & Thaler 1985 是长周期版；
#               短期版在 A 股更明显，通常归因于散户占比高、博弈性强）
#             ② 流动性补偿：短期暴跌常伴随抛压，抛压结束后价格回补
#             ③ 与"波动率/流动性"因子天然相关（跌得多的往往也是波动大、流动性差的）
# 计算细节  ：pct_change(20)；前 20 行 NaN，非 NaN 行数 = 总行数 − 20（实测 2819/2839）
# 常见坑    ：① 用**不复权**价算 → 除权日造出假暴跌，把"除权"错当成"跌得多"
#             ② 忘记 ffill → 停牌多的股票被静默剔除（样本有偏）
#             ③ 用 20 日信号却按年调仓 → 信号早就过期了
# 实测（全库，2015-2026，月频 T+1）：
#             多空（买层4卖层0）年化 16.38%、夏普 1.05、MDD -30.29%
#             IC +0.0623、ICIR 0.405、t 值 +4.78（139 期）、换手 71.9%/月
def rev_20d(panels: dict, params: dict) -> pd.DataFrame:
    """20 日反转：过去 20 个交易日的收益率（原始值，越大 = 涨越多）"""
    return _px(panels).pct_change(20, fill_method=None)


# =============================================================================
# 因子 3：mom_120d —— 6 个月动量
# =============================================================================
# 一句话    ：过去半年涨得多的，未来还涨（美股经典结论）。
# 公式      ：factor = close_t / close_{t-120} - 1
# 方向      ：sign = +1（越大越看多）→ 层4 = "过去半年涨最多" = 看多档
#             ⚠️ 注意：这个 sign 与三个反转因子**相反**，所以它们的层0/层4
#                含义要靠"定向后"的约定统一 —— 这就是 sign 存在的理由。
# 经济故事  ：① 信息扩散缓慢：好消息要几个月才被完全定价（反应不足）
#             ② 处置效应：赚了的急着卖、亏了的死扛 → 价格趋势被拖长
#             ③ 但 A 股（散户占比高、涨跌停多）常见的是**反转**而非动量，
#                实测这段样本里 mom_120d 就是负的（多空 -7.43%）
# 计算细节  ：pct_change(120)；params["skip"] > 0 时先 shift(skip) 再回看 120 天，
#             这就是经典的"12-1 动量"（跳过最近一个月，避免短期反转污染动量信号）
#             —— 用法：bt.py 里加 FACTOR_PARAMS = {"mom_120d": {"skip": 20}}
# 常见坑    ：① 不做 skip：最近 1 个月的短期反转会把动量信号"打折"
#             ② 把"动量在 A 股不成立"当成"代码写错了"——先看 IC 符号再说
# 实测（全库）：多空年化 -7.43%、夏普 -0.43、IC -0.0491、ICIR -0.313、换手 31.8%/月
def mom_120d(panels: dict, params: dict) -> pd.DataFrame:
    """6 个月动量（约 120 个交易日）；params["skip"] 可做 12-1 动量"""
    px = _px(panels)
    skip = int(params.get("skip", 0))
    return (px.shift(skip) if skip else px).pct_change(120, fill_method=None)


# =============================================================================
# 因子 4：vol_20d —— 20 日已实现波动率（低波动异象）
# =============================================================================
# 一句话    ：波动越低的股票，风险调整后收益越高。
# 公式      ：factor = std(日收益, 窗口=20)          （原始值：越大 = 越波动）
# 方向      ：sign = -1（越小越看多）→ 层4 = 最安静的 20% 股票
# 经济故事  ：① 彩票偏好：散户偏爱高波动股，把它买贵了 → 高波动未来收益低
#             ② 杠杆约束/机构行为：不愿加杠杆的机构去买低波动股 → 被买贵但更稳
#             ③ "低波动"在 A 股常和"大盘/银行地产"重叠 → 可能是市值/行业的代理变量
#                （所以下一步必须做行业/市值中性化，否则说不清你赚的是什么钱）
# 计算细节  ：日收益 → rolling(20, min_periods=20).std()
#             ⚠️ min_periods 必须显式写 20：不写的话前 19 天会用"半截窗口"算出
#                一个偏小的波动率 → 那 19 天的分层是错的（而且不报错！）
# 常见坑    ：① 用价格的标准差而不是**收益**的标准差（量纲完全不同）
#             ② 用了涨跌停日：限幅会把真实波动压住 → 波动率被低估（ST 股尤其明显）
#             ③ 忘记"低波动≈低换手"：实测 43.9%/月，比反转类低不少
# 实测（全库）：多空年化 12.20%、夏普 0.74、IC +0.0829、ICIR 0.430（IC 最高）、换手 43.9%/月
def vol_20d(panels: dict, params: dict) -> pd.DataFrame:
    """20 日已实现波动率；min_periods=20 保证不用"半截窗口"算出来的波动率"""
    return _px(panels).pct_change(fill_method=None).rolling(20, min_periods=20).std()


# =============================================================================
# 因子 5：ma_dev_20 —— 均线偏离（乖离率）
# =============================================================================
# 一句话    ：价格离 20 日均线越远，越容易往回走。
# 公式      ：factor = close / MA20 − 1，其中 MA20 = 过去 20 日收盘均值
# 方向      ：sign = -1 → 层4 = "离均线下方最远"（超跌），层0 = "上方最远"（超涨）
# 经济故事  ：本质是**短中期反转的另一种表达**：它把"过去 20 日收益"除以一个
#             近似等于期间均价的基准，所以和 rev_20d 相关性很高（实测两者夏普 1.00 vs 1.05）
#             它的额外信息是"价格的路径"：同样是涨 10%，单边直上 vs 反复震荡后上攻，
#             乖离率不同 → 可能捕捉"过热"程度
# 计算细节  ：rolling(20, min_periods=20).mean() 再相除；分母恒正（价格>0），但仍要
#             有"不填、不猜"的习惯：MA 还没算出来时因子就是 NaN，别 fillna
# 常见坑    ：① 用不复权价算 MA → 除权日 MA 突然跳变，乖离率失真
#             ② 和 rev_20d 一起当成两个独立因子（相关性极高，本质同一个）
# 实测（全库）：多空年化 15.18%、夏普 1.00、IC +0.0463、ICIR 0.319、换手 71.4%/月
def ma_dev_20(panels: dict, params: dict) -> pd.DataFrame:
    """均线偏离 = close / MA20 − 1（越大 = 离均线越远，通常在上方）"""
    px = _px(panels)
    ma = px.rolling(20, min_periods=20).mean()
    return px / ma - 1


# =============================================================================
# 因子 6：amihud_20 —— Amihud 非流动性（本批实测夏普最高）
# =============================================================================
# 一句话    ：单位成交额能推动多少价格？越"推得动"越不流动，越不流动越需要补偿。
# 公式      ：factor = mean( |日收益| / 成交额 , 窗口=20 )
#             含义：每 1 元成交额带来的价格波动幅度 —— 越大 = 越不流动
# 方向      ：sign = +1（越大越看多）→ 层4 = 最不流动的 20%
# 经济故事  ：① 🔶 Amihud (2002)：流动性差的股票必须有更高的预期收益来补偿
#               持有者"卖不出去"的风险 → 非流动性溢价
#             ② 在 A 股，非流动性又和"小市值、低关注度"高度重叠 →
#                这个因子很可能同时在捕捉**规模/壳价值/游资偏好**
#             ③ 它换手低（26.5%/月），是这批因子里对费率最友好的
# 计算细节  ：需要面板里的 "amount"（成交额，单位：元）；|r| / amount 之后取 20 日均值
#             ⚠️ 数值量级极小，但下游是**截面排名**，尺度不影响分层
# 常见坑    ：① amount 缺失/为 0 → 除零变 inf → 排名被污染（先想清楚怎么处理）
#             ② 把"非流动性溢价"直接说成"因子有效"：它和市值/流动性高度相关，
#                必须做中性化 + 相关性检验才能说这是独立的 alpha
#             ③ 停牌股 amount=0：虽然 can_trade 会拦住成交，但因子计算时要留意
# 实测（全库）：层4 年化 18.68%、多空年化 20.05%、夏普 1.32、MDD -31.14%、
#             IC +0.0660、ICIR 0.430、换手仅 26.5%/月
def amihud_20(panels: dict, params: dict) -> pd.DataFrame:
    """Amihud 非流动性 = mean(|日收益| / 成交额)；需要面板里有 amount"""
    r = _px(panels).pct_change(fill_method=None).abs()
    return (r / panels["amount"]).rolling(20, min_periods=20).mean()


